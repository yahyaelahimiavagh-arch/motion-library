"""Concatenate src/techniques*.js into assets/data.js (no build step is needed on the host)."""
import glob, re
fs = sorted(glob.glob('src/techniques*.js'), key=lambda f: int(re.sub(r'\D', '', f) or 1))
out = '/* generated by build.py - edit files in src/ instead */\n' + '\n'.join(open(f, encoding='utf-8').read() for f in fs)
open('assets/data.js', 'w', encoding='utf-8').write(out)
print('built assets/data.js from', len(fs), 'files,', len(out)//1024, 'KB')
